"""Complete original payment proof through the non-Spell physical hand tail.

This diagnostic tail is not a repeat acceptance window or gameplay checkpoint.
It closes after FinishPlay and all reactions generated by that completion.
"""
from .runtime_copy import deepcopy
from dataclasses import dataclass, replace

from .effects import Effect
from .model import (CardType, GameState, PaidHandClose, PaidHandInterruption,
                    PlayRecord, Event)
from .spell_cost_proof import HandPlayCostProof


KINDS = (CardType.MINION, CardType.WEAPON, CardType.HERO, CardType.LOCATION)


@dataclass(frozen=True)
class PaidHandCostProof(HandPlayCostProof):
    def __post_init__(self):
        if type(self.payment_state) is not GameState or type(self.prepared_play) is not PlayRecord:
            raise ValueError('Paid hand proof requires complete typed payment state and prepared root')
        play = self.prepared_play
        play.__post_init__()
        if (play.kind not in KINDS or play.submitted_cost is None or play.countered
                or play.completed or play.interrupted or play.paid_hand_close is not None
                or play.paid_hand_interrupt is not None or play.combo_submission_receipt_id is not None
                or play.combo_acceptance is not None or play.battlecry_acceptance is not None):
            raise ValueError('Paid hand proof requires the exact next prepared non-Spell root')
        from .rewind import HandSpellRewindAnchor
        for value in (self.rewind_anchor, self.rewind_session):
            if value is not None:
                if type(value) is not HandSpellRewindAnchor:
                    raise ValueError('Paid hand retry requires its real typed hand session')
                value.__post_init__()
        if self.rewind_anchor != (self.rewind_session if self.rewind_session is not None
                                 and self.rewind_session.attempt > 0 else None):
            raise ValueError('Paid hand retry quote and complete actual session disagree')


@dataclass(frozen=True)
class FinishPaidHandAcceptance(Effect):
    proof: PaidHandCostProof
    submission_base: GameState

    @property
    def play_id(self): return self.proof.prepared_play.id

    @property
    def submission_state(self):
        # Exact full post-append/pre-Combo state, represented by the genuine
        # postpayment base plus its one complete typed prepared append. The
        # base is independently a valid codec state before Combo exists.
        state = deepcopy(self.submission_base)
        from .play_history import commit_play
        commit_play(state, self.proof.prepared_play)
        return state

    def __post_init__(self):
        if type(self.proof) is not PaidHandCostProof or type(self.submission_base) is not GameState:
            raise ValueError('Paid hand tail requires complete original payment and submission states')
        self.proof.__post_init__()


def capture(r, prepared_play, quote):
    from .spell_cost_proof import _capture_hand_cost_proof
    return _capture_hand_cost_proof(r, prepared_play, quote, PaidHandCostProof)


def make_tail(r, proof, submission_base):
    tail = FinishPaidHandAcceptance(proof, submission_base)
    if tail.submission_state != r.state:
        raise ValueError('Paid hand submission operands differ from the actual successful append')
    validate_tail(tail, r.registry)
    return tail


def validate_tail(tail, registry):
    _validated_submission(tail, registry)


def _validated_submission(tail, registry):
    """Validate once and return a read-only submission for this check only."""
    from .spell_cost_proof import _validate_hand_cost_proof
    from .play_history import _project_commit_for_validation
    from .registry import Registry
    if type(tail) is not FinishPaidHandAcceptance:
        raise ValueError('Expected complete paid hand tail')
    tail.__post_init__()
    # No card callback or state writer receives this temporary view. The public
    # tail.submission_state property continues to return a fully detached copy.
    submission = (_project_commit_for_validation(tail.submission_base, tail.proof.prepared_play)
                  if type(registry) is Registry else tail.submission_state)
    _validate_hand_cost_proof(tail.proof, registry, submission_state=submission,
                             proof_type=PaidHandCostProof)
    return submission


def validate_history_prefix(original, state, registry):
    """All original fields stay fixed; only explicitly clocked closure may grow."""
    from .spell_acceptance import _bind_prefix_and_references
    from .owner_turns import validate_accepted_prefix
    _bind_prefix_and_references(original, state, registry)
    validate_accepted_prefix(original, state, registry)
    for old, new in zip(original.play_history, state.play_history):
        for name in ('paid_hand_close', 'paid_hand_interrupt'):
            before, after = getattr(old, name), getattr(new, name)
            if before is not None and before != after:
                raise ValueError('Original paid hand closure/interruption was rewritten')
            if before is None and after is not None and after.action < original.action_number:
                raise ValueError('Original paid hand progress contradicts its capture action')


def bind_live(state, tail, registry):
    submission = _validated_submission(tail, registry)
    return _bind_validated_submission(state, tail, registry, submission)


def original_target(r, play_id):
    """Original selected allocation from an actual still-live hand payment proof."""
    from .allocation_facts import SourceAllocationFact
    from .effects import _integer
    from .errors import ResolutionError
    _integer(play_id,'original paid target play',1)
    tails=tuple(work for work in r._work_queue if type(work) is FinishPaidHandAcceptance and work.play_id==play_id)
    if len(tails)!=1:raise ResolutionError('Original paid target requires its one active hand acceptance proof')
    tail=tails[0];record=bind_live(r.state,tail,r.registry)
    original=tail.proof.payment_state
    target=original.entities.get(record.target_id)
    if target is None:raise ResolutionError('Original paid target is absent from the actual payment state')
    return record,SourceAllocationFact.capture(original,target)


def _bind_validated_submission(state, tail, registry, submission):
    from .play_history import play_record
    validate_history_prefix(submission, state, registry)
    record = play_record(state, tail.play_id)
    if record.paid_hand_close is not None or record.paid_hand_interrupt is not None:
        raise ValueError('Active paid hand tail cannot be already closed or interrupted')
    return record


def owed(state):
    return [play.id for play in state.play_history if play.kind in KINDS
            and play.paid_hand_close is None and play.paid_hand_interrupt is None]


def validate_queue(state, registry, queue, *, game=None):
    from .resolver import FinishPlay, BehaviorCall
    from .repeat_windows import original_acceptance_windows
    from .end_turn_acceptance import _window_precedes
    from .spell_cost_proof import validate_hand_cost_proof_live
    tails = [(index, work) for index, work in enumerate(queue) if type(work) is FinishPaidHandAcceptance]
    if sorted(t.play_id for _,t in tails) != owed(state):
        raise ValueError('Paid hand queue lost, duplicated or borrowed an original payment tail')
    if tuple(t.play_id for _,t in tails) != tuple(reversed(owed(state))):
        raise ValueError('Nested paid hand roots must close in their genuine inner-first order')
    # All callees below are pure checks. Reuse local submissions only within
    # this invocation; the next effect/restore must validate its inputs again.
    submissions = {}
    for tail_index, tail in tails:
        submission = _validated_submission(tail, registry)
        submissions[tail_index] = submission
        record = _bind_validated_submission(state, tail, registry, submission)
        if game is not None: validate_hand_cost_proof_live(tail.proof, game)
        finishers = [(index,w) for index,w in enumerate(queue) if type(w) is FinishPlay and w.play_id == record.id]
        if (record.completed and finishers or not record.completed and
                (len(finishers) != 1 or finishers[0][0] >= tail_index)):
            raise ValueError('Paid hand acceptance must retain its unique prior physical FinishPlay')
        for index, work in enumerate(queue):
            if work is tail: continue
            contexts = [c for c,_,_ in original_acceptance_windows(work)]
            if type(work) is BehaviorCall: contexts.append(work.context)
            if any(context.play is not None and context.play.id == record.id for context in contexts):
                if index >= tail_index:
                    raise ValueError('Paid hand tail precedes its retained root callback or original acceptance control')
    for work in queue:
        if type(work) is BehaviorCall:
            validate_history_prefix(work.context.state, state, registry)
        for context, phase, identity in original_acceptance_windows(work):
            validate_history_prefix(context.state, state, registry)
            for tail_index, tail in tails:
                submission = submissions[tail_index]
                if _window_precedes(submission, context, phase, identity, registry, work):
                    continue
                if len(context.state.play_history) < tail.play_id:
                    raise ValueError('Later original window lost its complete submitted paid hand root')
                _bind_validated_submission(context.state, tail, registry, submission)
    return tuple(t.play_id for _,t in tails)


def validate_control_work(r, work):
    validate_queue(r.state, r.registry, (work, *r._work_queue), game=r.game)


def finish(r, tail):
    if r.game.runtime_audits:
        record = bind_live(r.state, tail, r.registry)
    else:
        from .play_history import play_record
        record = play_record(r.state, tail.play_id)
    if not record.completed or record.interrupted:
        raise ValueError('Paid hand tail precedes complete uninterrupted physical play')
    set_progress(r.state, record.id, close=PaidHandClose(r.state.action_number, len(r.game._events)))


def set_progress(state, play_id, *, close=None, interruption=None):
    """The sole monotonic paid tail update; never relax general play settlement."""
    from .play_history import play_record
    record = play_record(state, play_id)
    if (record.kind not in KINDS or record.submitted_cost is None
            or record.paid_hand_close is not None or record.paid_hand_interrupt is not None
            or (close is None) == (interruption is None)):
        raise ValueError('Paid hand progress must close or interrupt its unique still-owed tail')
    updated = replace(record, paid_hand_close=close, paid_hand_interrupt=interruption)
    updated.__post_init__()
    state.play_history[play_id-1] = updated


def validate_terminal_queue(r, queue):
    validate_queue(r.state, r.registry, tuple(queue), game=r.game)
    terminal = [event for event in r.game._events if event.kind == 'game_ended'
                and event.action == r.state.action_number]
    if owed(r.state) and len(terminal) != 1:
        raise ValueError('Interrupted paid hand roots require their actual pre-clear terminal event')
    if terminal:
        event = terminal[0]
        for play_id in owed(r.state):
            set_progress(r.state, play_id, interruption=PaidHandInterruption(event.action, event.sequence))


def validate_boundary(game):
    state = game._state
    from .spell_cost_proof import validate_compact_hand_costs
    for play in state.play_history:
        if play.kind not in KINDS: continue
        if play.submitted_cost is None:
            raise ValueError('Non-Spell physical hand root lost its complete submitted price')
        validate_compact_hand_costs(state, game.registry, play)
        for progress in (play.paid_hand_close, play.paid_hand_interrupt):
            if progress is not None and progress.action > state.action_number:
                raise ValueError('Paid hand progress is newer than its captured state')
        if play.paid_hand_close is not None:
            close = play.paid_hand_close
            if (close.event_cursor > len(game._events) or game._events[close.event_cursor-1].action != close.action):
                raise ValueError('Paid hand closing cursor differs from its actual event timeline')
        if play.paid_hand_interrupt is not None:
            interrupted = play.paid_hand_interrupt
            if (state.status == 'playing' or interrupted.game_ended_event > len(game._events)
                    or game._events[interrupted.game_ended_event-1].kind != 'game_ended'
                    or game._events[interrupted.game_ended_event-1].action != interrupted.action):
                raise ValueError('Paid hand interruption lost its genuine terminal event')
    if game._frame is None:
        if owed(state): raise ValueError('Stable game lost an unclosed non-Spell payment obligation')
    else:
        validate_choice_boundary(game)
        queue = (*game._frame.prefix, *game._frame.continuation)
        ids = validate_queue(state, game.registry, queue, game=game)
        if game._frame.paid_hand_acceptances != ids:
            raise ValueError('Suspended paid hand obligations differ from their complete ordered tails')


CHOICE_DIGEST = '_paid_hand_choice_boundary'


@dataclass(frozen=True)
class PaidHandChoiceBoundaryProof:
    """Complete genuine normalized request boundary, with no frame self-reference."""
    event: Event
    state: GameState
    work: tuple

    def __post_init__(self):
        if type(self.event) is not Event or type(self.state) is not GameState or type(self.work) is not tuple:
            raise ValueError('Choice payment boundary requires full typed event/state/work')
        from .effects import Effect
        from .resolver import BehaviorCall
        if any(not isinstance(item, (Effect, BehaviorCall)) for item in self.work):
            raise ValueError('Choice payment boundary work must contain only genuine interpreter work')
        from .continuations import FrameCodec
        from .serialization import event_to_dict
        FrameCodec._event(event_to_dict(self.event))
        event, choice = self.event, self.state.pending_choice
        if (event.kind != 'choice_requested' or choice is None or event.action != self.state.action_number
                or event.player_id != choice.player_id or event.source_id != choice.source_id
                or event.sequence < 1 or CHOICE_DIGEST in dict(event.data)):
            raise ValueError('Choice payment boundary is not its actual normalized pending request')
        data = dict(event.data)
        if (data.get('choice_id') != choice.id or data.get('option_ids') != tuple(o.id for o in choice.options)
                or data.get('min_count') != choice.min_count or data.get('max_count') != choice.max_count
                or data.get('purpose') != choice.purpose.value):
            raise ValueError('Choice payment boundary differs from the complete pending choice')
        for play in self.state.play_history:
            if play.paid_hand_close is not None and play.paid_hand_close.event_cursor >= event.sequence:
                raise ValueError('Originally closed paid root cannot close at or after its pending request')


def validate_choice_boundary_proof(proof, registry):
    if type(proof) is not PaidHandChoiceBoundaryProof:
        raise ValueError('Every suspended choice requires its complete payment boundary')
    proof.__post_init__()
    validate_queue(proof.state, registry, proof.work)


def choice_boundary_digest(proof, game, *, _state_memo=None):
    from .continuations import FrameCodec
    from .serialization import canonical_hash
    return canonical_hash(FrameCodec(game.mechanics, game.registry).encode_runtime(
        proof, readonly=True, _state_memo=_state_memo))


def capture_choice_boundary(r, event):
    # Called by emit AFTER its existing normalization, before the event is
    # appended/published or any listeners are captured. Nothing references the
    # frame or the resulting digest, and no extra gameplay checkpoint occurs.
    proof = PaidHandChoiceBoundaryProof(event, deepcopy(r.state), tuple(r._work_queue))
    # Debug audits this proof once at the completed waiting boundary.
    r._paid_hand_choice_boundary = proof
    from types import FunctionType
    from .registry_identity import _engine_kind
    handler = getattr(r, '_current_handler', None)
    # Native suspension does not execute queued work between this digest and
    # the frame capture. Extension handlers may still edit their own work.
    r._choice_frame_states = {} if type(handler) is FunctionType and _engine_kind(handler) else None
    return replace(event, data=tuple(sorted((*event.data,
        (CHOICE_DIGEST, choice_boundary_digest(proof, r.game, _state_memo=r._choice_frame_states))))))


def validate_choice_boundary(game, *, resume=False):
    frame, state = game._frame, game._state
    proof = frame.paid_hand_choice_boundary
    validate_choice_boundary_proof(proof, game.registry)
    event = proof.event
    expected_action = event.action + (1 if resume else 0)
    if (type(resume) is not bool or state.pending_choice != proof.state.pending_choice
            or event.sequence > len(game._events) or state.action_number != expected_action):
        raise ValueError('Suspended choice lost its complete original payment boundary')
    actual = game._events[event.sequence-1]
    digest = dict(actual.data).get(CHOICE_DIGEST)
    plain = replace(actual, data=tuple((key,value) for key,value in actual.data if key != CHOICE_DIGEST))
    if plain != event or digest != choice_boundary_digest(proof, game):
        raise ValueError('Suspended choice payment boundary differs from its actual request event')
    validate_history_prefix(proof.state, state, game.registry)
    original_tails = tuple(work for work in proof.work if type(work) is FinishPaidHandAcceptance)
    live_tails = tuple(work for work in (*frame.prefix,*frame.continuation)
                       if type(work) is FinishPaidHandAcceptance)
    if original_tails != live_tails or frame.paid_hand_acceptances != tuple(t.play_id for t in original_tails):
        raise ValueError('Suspended choice lost or rewrote its complete original owed payment tails')
    for tail in original_tails:
        old = proof.state.play_history[tail.play_id-1]
        current = state.play_history[tail.play_id-1]
        if (old.paid_hand_close is not None or old.paid_hand_interrupt is not None
                or current.paid_hand_close is not None or current.paid_hand_interrupt is not None):
            raise ValueError('A still-pending original choice cannot close its owed payment tail')
